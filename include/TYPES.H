/*
 * Fixed-width integer typedefs shared by every unit (u8, u16, u32, s16, s32; no owning src/ unit).
 * Requires nothing.
 */
#ifndef TYPES_H
#define TYPES_H

typedef unsigned char  u8;
typedef unsigned short u16;
typedef unsigned int   u32;
typedef short          s16;
typedef int            s32;

#endif
